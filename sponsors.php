<script>
/* =========================================================
   SPONSOR FORM INTERACTIONS
   ========================================================= */
document.addEventListener("DOMContentLoaded", function () {
    const categorySelect = document.getElementById("gtfSponsorCategory");
    const promoToggle = document.getElementById("gtfPromoToggle");
    const promoWrap = document.getElementById("gtfPromoInputWrap");
    const promoInput = document.getElementById("gtfPromoCode");

    // Show or hide promo code field.
    if (promoToggle && promoWrap) {
        promoToggle.addEventListener("change", function () {
            promoWrap.hidden = !this.checked;

            if (!this.checked && promoInput) {
                promoInput.value = "";
            }
        });
    }

    // Preselect a package when an enquiry link is clicked.
    document.querySelectorAll(
        ".gtf-package-btn, .gtf-exhibition-btn, .gtf-showcase-btn"
    ).forEach(function (link) {
        link.addEventListener("click", function () {
            const selectedPackage = this.getAttribute("data-package");

            if (categorySelect && selectedPackage) {
                categorySelect.value = selectedPackage;
            }
        });
    });

    // Basic client-side logo extension check.
    const logoInput = document.getElementById("gtfSponsorLogo");

    if (logoInput) {
        logoInput.addEventListener("change", function () {
            const file = this.files && this.files[0];

            if (!file) {
                return;
            }

            const allowedExtensions = ["jpg", "jpeg", "gif", "png"];
            const extension = file.name.split(".").pop().toLowerCase();

            if (!allowedExtensions.includes(extension)) {
                this.value = "";
                alert("Please upload a logo in JPG, JPEG, GIF, or PNG format.");
            }
        });
    }
});
</script>


